def validate_egress_url(
    name: str,
    url: str,
    *,
    require_v1: bool = False,
    allow_localhost: bool = False,
) -> str:
    """Reject endpoint URLs that Pier's trial egress proxy cannot reach."""
    parsed = urlparse(url)
    if parsed.scheme not in PIER_EGRESS_PORTS:
        raise SystemExit(f"{name} must be http:// or https://, got {url!r}")
    host = (parsed.hostname or "").rstrip(".")
    if not host:
        raise SystemExit(f"{name} has no host: {url!r}")
    # Pier derives the Squid allowlist from configured endpoint hostnames.
    # Dotless names are discarded by hostname_from_url(), so they would make
    # every request fail at the firewall rather than at the provider.
    if "." not in host and host != "localhost":
        raise SystemExit(
            f"{name} host {host!r} is a dotless bare name. Pier drops it from "
            "the egress allowlist; use an IP address or an FQDN."
        )
    if host == "localhost" and not allow_localhost:
        raise SystemExit(
            f"{name} cannot use localhost from a trial container; use the "
            "gateway IP/FQDN visible from Docker."
        )
    port = parsed.port or PIER_EGRESS_PORTS[parsed.scheme]
    if port != PIER_EGRESS_PORTS[parsed.scheme]:
        raise SystemExit(
            f"{name} port {port} is unreachable from a trial container. "
            "Pier's egress proxy allows only HTTP on 80 and HTTPS on 443."
        )
    if require_v1 and not parsed.path.rstrip("/").endswith("/v1"):
        raise SystemExit(f"{name} should end in /v1, got {url!r}")
    return url.rstrip("/")


def validate_bridge_url(url: str) -> str:
    """Reject bridge URLs that Pier's egress policy cannot reach."""
    return validate_egress_url(
        "CODEX_CLIPROXY_BASE_URL",
        url,
        require_v1=True,
        allow_localhost=True,
    )


def yaml_quote(value: str) -> str:
    """Quote one scalar for the generated CLIProxyAPI config."""
    return json.dumps(value)


def cliproxy_model_block(entry: dict[str, object]) -> list[str]:
    """Render a CLIProxyAPI model from its generated Codex catalog entry.

    Deriving the reasoning levels from the Codex catalog rather than restating
    them is the point of this function. CLIProxyAPI snaps an incoming
    ``reasoning.effort`` to the nearest level it knows about, and its default
    level set is low/medium/high, so a model left undeclared would silently
    downgrade PA1's ``max`` requests to ``high``.
    """
    levels = [
        str(level["effort"])
        for level in entry["supported_reasoning_levels"]  # type: ignore[index]
    ]
    slug = str(entry["slug"])
    lines = [
        f"      - name: {yaml_quote(slug)}",
        f"        alias: {yaml_quote(slug)}",
        f"        display-name: {yaml_quote(str(entry['display_name']))}",
        f"        max-context-length: {int(entry['context_window'])}",
        "        input-modalities: ["
        + ", ".join(str(modality) for modality in entry["input_modalities"])  # type: ignore[index]
        + "]",
        "        thinking:",
        "          levels: [" + ", ".join(yaml_quote(level) for level in levels) + "]",
    ]
    return lines


def cliproxy_config(
    *,
    bridge_api_key: str,
    litellm_url: str,
    litellm_api_key: str,
    thirdparty_entries: list[dict[str, object]],
    zai_entry: dict[str, object],
    zai_api_key: str,
    opus_entry: dict[str, object] | None,
    anthropic_api_key: str | None,
    request_log: bool,
) -> str:
    """Fill the tracked CLIProxyAPI template with this deployment's secrets.

    The config is generated rather than mounted directly only because
    CLIProxyAPI does no environment interpolation, so every credential has to be
    a literal in the file it reads. Everything else stays in the tracked
    template where it can be reviewed.
    """
    if bridge_api_key in CLIPROXY_EXAMPLE_KEYS:
        raise SystemExit(
            "CODEX_CLIPROXY_API_KEY is one of CLIProxyAPI's example keys; "
            "CLIProxyAPI would disable every /v1 route. Choose your own value."
        )

    template = template_body(CLIPROXY_TEMPLATE, CLIPROXY_TEMPLATE.read_text())
    template = "\n".join(CLIPROXY_GENERATED_HEADER) + "\n" + template
    verify_cliproxy_models(
        CLIPROXY_TEMPLATE, template, [*thirdparty_entries, zai_entry]
    )

    values = {
        "__CODEX_CLIPROXY_API_KEY__": bridge_api_key,
        "__LITELLM_API_KEY__": litellm_api_key,
        "__LITELLM_OPENAI_BASE_URL__": litellm_url.rstrip("/"),
        "__ZAI_API_KEY__": zai_api_key,
        "__REQUEST_LOG__": request_log,
    }

    if opus_entry is not None:
        if not anthropic_api_key:
            raise SystemExit("Missing required environment variable: ANTHROPIC_API_KEY")
        fragment = template_body(
            CLIPROXY_OPUS_TEMPLATE, CLIPROXY_OPUS_TEMPLATE.read_text()
        )
        verify_cliproxy_models(CLIPROXY_OPUS_TEMPLATE, fragment, [opus_entry])
        template = template.rstrip("\n") + "\n\n" + fragment.lstrip("\n")
        values["__ANTHROPIC_API_KEY__"] = anthropic_api_key

    return substitute_sentinels(template, values)


def template_body(path: Path, template: str) -> str:
    """Return the part of a template that is written to the generated config.

    Each template opens with notes aimed at a reader of the repository, which
    should not end up in the file CLIProxyAPI reads. The delimiter marks where
    that preamble stops; comments below it are kept, because several of them are
    warnings that matter to whoever is debugging a run.
    """
    marker = f"{CLIPROXY_TEMPLATE_DELIMITER}\n"
    if template.count(marker) != 1:
        raise SystemExit(
            f"{path}: expected exactly one {CLIPROXY_TEMPLATE_DELIMITER!r} line"
        )
    return template.split(marker, 1)[1]


def substitute_sentinels(template: str, values: dict[str, object]) -> str:
    """Replace each quoted `"__SENTINEL__"` scalar, then reject leftovers.

    Sentinels are quoted in the template so it stays valid YAML on its own, and
    the whole quoted scalar is replaced so credentials are escaped properly
    rather than pasted in raw.
    """
    rendered = template
    for sentinel, value in values.items():
        quoted = f'"{sentinel}"'
        if rendered.count(quoted) != 1:
            raise SystemExit(
                f"CLIProxyAPI template: expected exactly one {quoted}, "
                f"found {rendered.count(quoted)}"
            )
        replacement = (
            ("true" if value else "false")
            if isinstance(value, bool)
            else yaml_quote(str(value))
        )
        rendered = rendered.replace(quoted, replacement)
    # Comment lines are skipped: the template documents its own sentinel syntax.
    body = "\n".join(
        line for line in rendered.splitlines() if not line.lstrip().startswith("#")
    )
    if leftover := re.findall(r"__[A-Z0-9_]+__", body):
        raise SystemExit(
            f"CLIProxyAPI template has unresolved placeholders: {sorted(set(leftover))}"
        )
    return rendered


def verify_cliproxy_models(
    path: Path, template: str, entries: list[dict[str, object]]
) -> None:
    """Fail if the template's model blocks disagree with the Codex catalog.

    This is the invariant that keeps the bridge honest. CLIProxyAPI snaps an
    incoming `reasoning.effort` to the nearest level it knows about, and its
    default level set is low/medium/high, so a model whose levels omit `max`
    would silently downgrade PA1's `max` requests to `high`. Rendering the
    expected block from the same catalog entry the Codex side uses, and
    requiring the template to contain it verbatim, means the two cannot drift.
    """
    for entry in entries:
        block = "\n".join(cliproxy_model_block(entry))
        if block not in template:
            raise SystemExit(
                f"{path}: the block for {entry['slug']!r} does not match the "
                f"frozen Codex catalog. Expected to find:\n{block}"
            )


def render_model_config(path: Path, base_url: str, expected_sentinels: int) -> str:
    """Insert the LiteLLM URL and reject stale/missing Pi endpoint sentinels."""
    template = path.read_text()
    actual_sentinels = template.count(PI_BASE_URL_SENTINEL)
    if actual_sentinels != expected_sentinels:
        raise SystemExit(
            f"{path}: expected {expected_sentinels} {PI_BASE_URL_SENTINEL} "
            f"placeholder(s), found {actual_sentinels}"
        )
    rendered = template.replace(PI_BASE_URL_SENTINEL, base_url.rstrip("/"))
    if PI_BASE_URL_SENTINEL in rendered:
        raise SystemExit(f"{path}: unresolved {PI_BASE_URL_SENTINEL} placeholder")
    return rendered


def validate_pi_fireworks_compat(path: Path, rendered: str) -> None:
    """Keep provider-specific request extensions off Fireworks-backed Pi routes."""
    if "  - name: pi\n" not in rendered:
        return

    if "model_name: zai/glm-5p3-flash" in rendered:
        required = (
            "thinkingFormat: openai",
            "zaiToolStream: false",
        )
        missing = [item for item in required if item not in rendered]
        if missing:
            raise SystemExit(
                f"{path}: GLM Pi Fireworks profile is missing "
                + ", ".join(repr(item) for item in missing)
            )
        if "zaiToolStream: true" in rendered:
            raise SystemExit(
                f"{path}: GLM Pi must not send Z.AI-only tool_stream to Fireworks"
            )



OPENCODE_V2_AGENT_BLOCK = r"(?ms)^  - name: opencode-v2\b.*?(?=^  - name:|\Z)"
OPENCODE_V2_ZAI_TRANSPORT = ("zai", "zai-coding-plan", "zhipuai", "zhipuai-coding-plan")


def _opencode_v2_agent_blocks(rendered: str) -> list[str]:
    """Return one comment-free text block per ``opencode-v2`` agent.

    Every check below is per owning agent: a compliant sibling must not satisfy
    a requirement for an agent that omits it, and prose in a comment must not
    stand in for a declaration.
    """
    blocks = []
    for block in re.findall(OPENCODE_V2_AGENT_BLOCK, rendered):
        blocks.append(
            "\n".join(
                line for line in block.splitlines() if not line.lstrip().startswith("#")
            )
        )
    return blocks


def _require(path: Path, label: str, block: str, needles) -> None:
    missing = [
        needle
        for needle in needles
        if not (
            re.search(needle[1], block, re.MULTILINE)
            if isinstance(needle, tuple)
            else needle in block
        )
    ]
    if missing:
        raise SystemExit(
            f"{path}: OpenCode V2 {label} is missing "
            + ", ".join(
                repr(item[0] if isinstance(item, tuple) else item) for item in missing
            )
        )


def validate_opencode_v2_config(path: Path, rendered: str) -> None:
    """Validate the OpenCode V2 smoke profiles at generation time.

    OpenCode's JSON schema accepts both ``limit.output`` metadata and a model
    request ``body``.  The former alone did not put an output cap on the wire
    (PA1 #40), so silently dropping this body override would turn a generated
    smoke job into an unbounded probe.  Keep these checks text-based to
    preserve the generator's zero-runtime-dependency contract and to catch
    conflicting reasoning controls before any deployment files are written.

    The model-specific checks are keyed on the agent's own ``model_name``, not
    on the file name, so every GLM profile is covered rather than only
    ``smoke.yaml``.
    """
    if "opencode_v2_config:" not in rendered:
        return
    blocks = _opencode_v2_agent_blocks(rendered)
    if not blocks:
        raise SystemExit(f"{path}: OpenCode V2 config declares no opencode-v2 agent")
    # Acceptance-only smoke jobs additionally pin the cheap settings their
    # headers document; the primary profiles use their own values.
    is_smoke = "configs/opencode-v2/" in path.as_posix()
    # The smoke exists to exercise every provider surface used by the current
    # OpenCode V2 benchmark routes.
    if is_smoke and path.name == "smoke.yaml":
        for model in (
            "zai/glm-5.3-flash",
            "openai/gpt-5.6-luna",
            "deepseek/deepseek-v4p1-flash",
        ):
            if not any(
                re.search(
                    rf"^\s+model_name: {re.escape(model)}$", block, re.MULTILINE
                )
                for block in blocks
            ):
                raise SystemExit(
                    f"{path}: the OpenCode V2 smoke job must cover every current "
                    f"provider surface; no agent declares {model}"
                )

    for block in blocks:
        _require(
            path,
            "agent",
            block,
            [
                "restrict_model: true",
                "opencode_v2_checksums:",
                "model_catalog_file: benchmark/references/"
                "opencode-v2-model-catalog-2.0.8.json",
                ("variant: <effort>", r"^\s+variant: \S+$"),
                # Release selection belongs to each job, not this generator.
                (
                    "exact version pin (x.y.z)",
                    r"^\s+version:\s*[\"\']?\d+\.\d+\.\d+(?:-[\w.-]+)?[\"\']?\s*$",
                ),
                ("linux-x64 SHA-256", r"^\s+linux-x64:\s*[0-9a-f]{64}\s*$"),
                ("linux-arm64 SHA-256", r"^\s+linux-arm64:\s*[0-9a-f]{64}\s*$"),
                # Every agent declares its own web-search policy (PA1 #48).
                ("websearch:", r"^\s+websearch:"),
                ("baseURL:", r"^\s+baseURL: \S+"),
            ],
        )

        if re.search(r"^\s+model_name: zai/glm-5\.3-flash$", block, re.MULTILINE):
            direct_zai = (
                "ZHIPU_API_KEY: ${ZAI_API_KEY}" in block
                and "baseURL: https://api.z.ai/api/coding/paas/v4" in block
            )
            if direct_zai:
                _require(
                    path,
                    "direct Z.AI GLM profile",
                    block,
                    [
                        "ZHIPU_API_KEY: ${ZAI_API_KEY}",
                        "baseURL: https://api.z.ai/api/coding/paas/v4",
                        ("glm-5.3-flash model entry", r"^\s+glm-5\.3-flash:\s*$"),
                        ("body max_tokens cap", r"^\s+max_tokens: \d+$"),
                    ],
                )
                for forbidden in (
                    '@opencode/ai/providers/fireworks',
                    "canonical: fireworks",
                    "modelID: glm-5p3-flash",
                ):
                    if forbidden in block:
                        raise SystemExit(
                            f"{path}: direct Z.AI GLM smoke must not contain {forbidden!r}"
                        )
                if is_smoke:
                    _require(
                        path,
                        "direct Z.AI GLM smoke profile",
                        block,
                        ["variant: low", "max_tokens: 8192"],
                    )
            else:
                _require(
                    path,
                    "GLM profile",
                    block,
                    [
                        'package: "@opencode/ai/providers/fireworks"',
                        "canonical: fireworks",
                        ("glm-5.3-flash model entry", r"^\s+glm-5\.3-flash:\s*$"),
                        "modelID: glm-5p3-flash",
                        "maxTokensField: max_tokens",
                        "reasoningField: reasoning_content",
                        ("reasoningEffort:", r"^\s+reasoningEffort: \S+$"),
                        ("body max_tokens cap", r"^\s+max_tokens: \d+$"),
                    ],
                )
                if re.search(r"^\s+thinking:", block, re.MULTILINE):
                    raise SystemExit(
                        f"{path}: GLM must use reasoningEffort alone; "
                        "do not add a conflicting thinking control"
                    )
                if is_smoke:
                    _require(
                        path,
                        "GLM smoke profile",
                        block,
                        ["variant: low", "reasoningEffort: low", "max_tokens: 8192"],
                    )

        if re.search(r"^\s+model_name: openai/gpt-5\.6-luna$", block, re.MULTILINE):
            _require(
                path,
                "Luna profile",
                block,
                [
                    ("gpt-5.6-luna model entry", r"^\s+gpt-5\.6-luna:\s*$"),
                    # Luna keeps the built-in Responses profile, whose output
                    # field is max_output_tokens (PA1 #40).
                    ("body max_output_tokens cap", r"^\s+max_output_tokens: \d+$"),
                ],
            )
            if is_smoke:
                _require(
                    path,
                    "Luna smoke profile",
                    block,
                    ["variant: low", "max_output_tokens: 8192"],
                )

        if re.search(
            r"^\s+model_name: deepseek/deepseek-v4p1-flash$",
            block,
            re.MULTILINE,
        ):
            _require(
                path,
                "DeepSeek profile",
                block,
                [
                    'package: "@opencode/ai/providers/fireworks"',
                    ("DeepSeek model entry", r"^\s+deepseek-v4p1-flash:\s*$"),
                    "modelID: deepseek-v4p1-flash",
                    "maxTokensField: max_tokens",
                    "reasoningField: reasoning_content",
                    ("reasoningEffort:", r"^\s+reasoningEffort: \S+$"),
                    ("body max_tokens cap", r"^\s+max_tokens: \d+$"),
                ],
            )
            if is_smoke:
                _require(
                    path,
                    "DeepSeek smoke profile",
                    block,
                    ["variant: low", "reasoningEffort: low", "max_tokens: 8192"],
                )

    validate_opencode_v2_tool_stream(path, rendered)


def validate_opencode_v2_tool_stream(path: Path, rendered: str) -> None:
    """Keep the Z.AI-only ``tool_stream`` extension off the gateway wire.

    OpenCode 2.0.8 injects ``tool_stream: true`` whenever the resolved
    transport provider is zai/zhipuai and the request carries tools. The
    Fireworks-backed PA1 route rejects that field with HTTP 400 before any
    token is spent, so a profile that keeps the canonical ``zai`` provider id
    must redirect ``canonical`` at the Fireworks transport. There is no
    model-level override: ``zaiToolStream`` is absent from OpenCode's config
    schema.
    """
    blocks = _opencode_v2_agent_blocks(rendered) or [
        "\n".join(
            line for line in rendered.splitlines() if not line.lstrip().startswith("#")
        )
    ]
    for block in blocks:
        declared = [
            provider
            for provider in OPENCODE_V2_ZAI_TRANSPORT
            if re.search(rf"^\s+{re.escape(provider)}:\s*$", block, re.MULTILINE)
        ]
        if not declared:
            continue
        # Native Z.AI Coding Plan routes are allowed to use Z.AI's tool_stream
        # behavior. Only Fireworks-backed zai identities need the redirect.
        if "baseURL: https://api.z.ai/api/coding/paas/v4" in block:
            continue
        if not re.search(r"^\s+canonical:\s*fireworks\s*$", block, re.MULTILINE):
            raise SystemExit(
                f"{path}: an OpenCode V2 profile using the "
                f"{', '.join(declared)} provider id must set canonical: fireworks, "
                "otherwise OpenCode 2.0.8 sends tool_stream:true and the gateway "
                "returns HTTP 400"
            )

def _model_limit_values(rendered: str, model_id: str) -> dict[str, int]:
    """Read one model's integer limit block without adding a YAML dependency."""
    lines = rendered.splitlines()
    model_index = next(
        (
            index
            for index, line in enumerate(lines)
            if line.strip() == f"{model_id}:"
        ),
        None,
    )
    if model_index is None:
        raise SystemExit(f"OpenCode V2 profile is missing model {model_id!r}")
    model_indent = len(lines[model_index]) - len(lines[model_index].lstrip())
    limit_index = None
    for index in range(model_index + 1, len(lines)):
        stripped = lines[index].strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(lines[index]) - len(lines[index].lstrip())
        if indent <= model_indent:
            break
        if stripped == "limit:":
            limit_index = index
            break
    if limit_index is None:
        raise SystemExit(f"OpenCode V2 model {model_id!r} is missing limit")
    limit_indent = len(lines[limit_index]) - len(lines[limit_index].lstrip())
    values: dict[str, int] = {}
    for line in lines[limit_index + 1 :]:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        if indent <= limit_indent:
            break
        match = re.fullmatch(r"(context|input|output):\s*([0-9]+)", stripped)
        if match:
            values[match.group(1)] = int(match.group(2))
    return values


def validate_primary_opencode_v2_profile(
    path: Path, rendered: str, model_ref: str, *, require_input: bool = False
) -> None:
    """Validate a primary built-in profile and its minimal route overrides."""
    if f"model_name: {model_ref}" not in rendered or "#" in rendered.split(
        "model_name:", 1
    )[1].splitlines()[0]:
        raise SystemExit(
            f"{path}: OpenCode V2 model_name must be the built-in {model_ref} "
            "reference with variant supplied separately in kwargs"
        )
    if "variant: max" not in rendered:
        raise SystemExit(
            f"{path}: {model_ref} must set kwargs.variant: max"
        )
    provider, _ = model_ref.split("/", 1)
    provider_block = f"        {provider}:"
    if provider_block not in rendered:
        raise SystemExit(
            f"{path}: {model_ref} must override the built-in {provider} "
            "provider transport settings"
        )
    if model_ref == "moonshotai/kimi-k3":
        required = (
            "websearch:\n        provider: random",
            'package: "@opencode/ai/providers/fireworks"',
            "models:\n            kimi-k3:",
            "reasoningField: reasoning_content",
            "max_tokens: 131072",
        )
    elif model_ref == "deepseek/deepseek-v4p1-flash":
        required = (
            "websearch: false",
            'package: "@opencode/ai/providers/fireworks"',
            "models:\n            deepseek-v4p1-flash:",
            "modelID: deepseek-v4p1-flash",
            "reasoningField: reasoning_content",
            "max_tokens: 384000",
            "reasoningEffort: max",
        )
    elif model_ref == "openai/gpt-5.6-luna":
        required = (
            "websearch: false",
            "models:\n            gpt-5.6-luna:",
            "max_output_tokens: 128000",
        )
    else:
        raise SystemExit(f"{path}: unsupported primary OpenCode V2 model {model_ref!r}")
    missing = [needle for needle in required if needle not in rendered]
    if missing:
        raise SystemExit(
            f"{path}: {model_ref} is missing inherited-profile override(s): "
            + ", ".join(repr(item) for item in missing)
        )

    if require_input:
        limits = _model_limit_values(rendered, model_ref.rsplit("/", 1)[1])
        input_limit = limits.get("input")
        context_limit = limits.get("context")
        if input_limit is None or context_limit is None:
            raise SystemExit(
                f"{path}: {model_ref} must declare both input and context limits"
            )
        if input_limit > context_limit:
            raise SystemExit(
                f"{path}: {model_ref} input limit {input_limit} exceeds "
                f"context limit {context_limit}"
            )


def _validate_primary_explicit_profile(
    path: Path, rendered: str, model_ref: str, variant: str
) -> None:
    """Validate the explicit frozen-catalogue exception or direct Anthropic profile."""
    required = (
        f"model_name: {model_ref}",
        f"variant: {variant}",
        "websearch: false",
    )
    missing = [needle for needle in required if needle not in rendered]
    if missing:
        raise SystemExit(
            f"{path}: primary profile is missing "
            + ", ".join(repr(item) for item in missing)
        )
    if model_ref == "zai/glm-5.3-flash":
        if path.name == "glm-5.3-sub.yaml":
            required_glm = (
                "ZHIPU_API_KEY: ${ZAI_API_KEY}",
                "providers:\n          zai:",
                "baseURL: https://api.z.ai/api/coding/paas/v4",
            )
            forbidden = (
                '@opencode/ai/providers/fireworks',
                "canonical: fireworks",
                "modelID: glm-5p3-flash",
            )
            missing_glm = [needle for needle in required_glm if needle not in rendered]
            present_forbidden = [needle for needle in forbidden if needle in rendered]
            if missing_glm or present_forbidden:
                detail = missing_glm + [f"forbidden {item}" for item in present_forbidden]
                raise SystemExit(
                    f"{path}: direct Z.AI GLM profile mismatch: "
                    + ", ".join(repr(item) for item in detail)
                )
        else:
            required_glm = (
                'package: "@opencode/ai/providers/fireworks"',
                "models:\n            glm-5.3-flash:",
                "modelID: glm-5p3-flash",
                "reasoningField: reasoning_content",
                "max_tokens: 131072",
                "reasoningEffort: low",
                "reasoningEffort: high",
                "reasoningEffort: max",
            )
            missing_glm = [needle for needle in required_glm if needle not in rendered]
            if missing_glm:
                raise SystemExit(
                    f"{path}: GLM explicit profile is missing "
                    + ", ".join(repr(item) for item in missing_glm)
                )


def validate_primary_opencode_v2_profiles() -> None:
    """Validate all primary profiles before generating deployment files."""
    for filename, model_id in PRIMARY_OPENCODE_V2_MODELS.items():
        path = BENCHMARK_DIR / "configs" / "opencode-v2" / filename
        validate_primary_opencode_v2_profile(
            path,
            path.read_text(),
            model_id,
            require_input=filename == "luna.yaml",
        )
    explicit_profiles = {
        "glm-5.3-flash.yaml": ("zai/glm-5.3-flash", "max"),
        "glm-5.3-sub.yaml": ("zai/glm-5.3-flash", "max"),
        "opus.yaml": ("anthropic/claude-opus-5", "medium"),
    }
    for filename, (model_ref, variant) in explicit_profiles.items():
        path = BENCHMARK_DIR / "configs" / "opencode-v2" / filename
        _validate_primary_explicit_profile(path, path.read_text(), model_ref, variant)


def validate_claude_output_policy() -> None:
    """Keep Claude Code on its native per-model output-token behavior."""
    offenders = [
        path.name
        for path in sorted(CONFIG_DIR.glob("*.yaml"))
        if CLAUDE_OUTPUT_OVERRIDE in path.read_text()
    ]
    if offenders:
        joined = ", ".join(offenders)
        raise SystemExit(
            f"Remove {CLAUDE_OUTPUT_OVERRIDE} from benchmark configs: {joined}. "
            "PA1 intentionally leaves Claude Code's output limit unset."
        )


def main() -> None:
    """Generate endpoint-dependent Pi and Codex configuration files."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--env-file", type=Path)
    parser.add_argument(
        "--include-opus",
        action="store_true",
        help="also generate the active Codex Opus catalog and bridge route",
    )
    args = parser.parse_args()
    if args.env_file:
        load_env_file(args.env_file)

    validate_claude_output_policy()
    validate_primary_opencode_v2_profiles()

    litellm_url = validate_egress_url(
        "LITELLM_OPENAI_BASE_URL",
        require("LITELLM_OPENAI_BASE_URL"),
        require_v1=True,
    )
    validate_egress_url(
        "LITELLM_ANTHROPIC_BASE_URL",
        require("LITELLM_ANTHROPIC_BASE_URL"),
    )
    litellm_api_key = require("LITELLM_API_KEY")
    zai_api_key = require("ZAI_API_KEY")
    bridge_url = validate_bridge_url(require("CODEX_CLIPROXY_BASE_URL"))
    # Claude Code reaches the same bridge without /v1 (Luna and the DeepSeek
    # CLIProxyAPI rerun), so an unset or unreachable value must fail here.
    validate_egress_url(
        "CODEX_CLIPROXY_ANTHROPIC_BASE_URL",
        require("CODEX_CLIPROXY_ANTHROPIC_BASE_URL"),
        allow_localhost=True,
    )
    bridge_api_key = require("CODEX_CLIPROXY_API_KEY")
    request_log = os.environ.get("CODEX_CLIPROXY_REQUEST_LOG", "").strip().lower() in {
        "1",
        "true",
        "yes",
    }

    # Build and validate every output before touching benchmark/generated. A bad
    # frozen catalog or template therefore cannot leave a half-updated run set.
    rendered_models: list[tuple[Path, str]] = []
    for name, expected_sentinels in CURRENT_MODEL_CONFIGS.items():
        source = CONFIG_DIR / name
        destination = GENERATED_DIR / name
        rendered = render_model_config(source, litellm_url, expected_sentinels)
        validate_pi_fireworks_compat(source, rendered)
        if name.startswith("opencode-v2/"):
            validate_opencode_v2_config(source, rendered)
        rendered_models.append(
            (
                destination,
                rendered,
            )
        )

    sol_profile = load_codex_sol_profile()
    thirdparty_entries = [
        deepseek_codex_entry(sol_profile),
        kimi_codex_entry(sol_profile),
        glm_codex_entry(sol_profile),
    ]
    catalog_json = json.dumps({"models": thirdparty_entries}, indent=2) + "\n"
    zai_entry = glm_zai_codex_entry(sol_profile)
    zai_catalog_json = json.dumps({"models": [zai_entry]}, indent=2) + "\n"

    # Retained as the control for issue #31: this is the direct corporate-gateway
    # Codex route that Fireworks rejects. No current job references it.
    litellm_toml = provider_toml("litellm", "LiteLLM", litellm_url, "LITELLM_API_KEY")
    # Luna keeps Codex's reserved built-in OpenAI provider. Codex 0.151.0
    # rejects [model_providers.openai]; Pier supplies openai_base_url from
    # OPENAI_BASE_URL on the command line, so this file only selects the
    # built-in provider and disables web search.
    openai_no_web_search_toml = (
        'preferred_auth_method = "apikey"\n'
        'forced_login_method = "api"\n'
        'model_provider = "openai"\n'
        'web_search = "disabled"\n'
    )
    # The route every third-party Codex job actually uses.
    bridge_toml = provider_toml(
        "cliproxy", "CLIProxyAPI", bridge_url, "CODEX_CLIPROXY_API_KEY"
    )
    bridge_no_web_search_toml = provider_toml(
        "cliproxy",
        "CLIProxyAPI",
        bridge_url,
        "CODEX_CLIPROXY_API_KEY",
        disable_web_search=True,
    )

    opus_entry = opus_codex_entry(sol_profile) if args.include_opus else None
    opus_catalog_json = (
        json.dumps({"models": [opus_entry]}, indent=2) + "\n"
        if opus_entry is not None
        else None
    )
    bridge_config = cliproxy_config(
        bridge_api_key=bridge_api_key,
        litellm_url=litellm_url,
        litellm_api_key=litellm_api_key,
        thirdparty_entries=thirdparty_entries,
        zai_entry=zai_entry,
        zai_api_key=zai_api_key,
        opus_entry=opus_entry,
        anthropic_api_key=os.environ.get("ANTHROPIC_API_KEY", "").strip() or None,
        request_log=request_log,
    )

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    # request-log records prompts and unredacted Authorization headers, so the
    # directory must be owner-only — including when it already exists.
    logs_dir = GENERATED_DIR / "cliproxy-logs"
    logs_dir.mkdir(mode=0o700, exist_ok=True)
    logs_dir.chmod(0o700)
    for obsolete in (
        "pi.yaml",
        "codex-provenance.json",
        "codex-opus.toml",
    ):
        (GENERATED_DIR / obsolete).unlink(missing_ok=True)

    for path, contents in rendered_models:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
        print(f"Wrote {path}")

    for name, contents in (
        ("codex-litellm.toml", litellm_toml),
        ("codex-openai-no-web-search.toml", openai_no_web_search_toml),
        ("codex-cliproxy.toml", bridge_toml),
        ("codex-cliproxy-no-web-search.toml", bridge_no_web_search_toml),
        ("codex-thirdparty-models.json", catalog_json),
        ("codex-glm-zai-models.json", zai_catalog_json),
    ):
        path = GENERATED_DIR / name
        path.write_text(contents)
        print(f"Wrote {path}")

    bridge_config_path = GENERATED_DIR / "cliproxy-config.yaml"
    # Tighten the mode before the credentials are written, not after.
    bridge_config_path.touch(mode=0o600, exist_ok=True)
    bridge_config_path.chmod(0o600)
    bridge_config_path.write_text(bridge_config)
    print(f"Wrote {bridge_config_path}")

    opus_catalog_path = GENERATED_DIR / "codex-opus-models.json"
    if opus_catalog_json is None:
        opus_catalog_path.unlink(missing_ok=True)
        return
    opus_catalog_path.write_text(opus_catalog_json)
    print(f"Wrote {opus_catalog_path}")


if __name__ == "__main__":
    main()
